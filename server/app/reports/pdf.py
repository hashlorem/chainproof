# The "Examiner" light theme (docs/REDESIGN.md): the web app's light tokens, rules between rows instead of a grid,
# left-aligned headings. Colour only for meaning: green = verified, red = a problem.
INK, MUTED, RULE = colors.HexColor("#1d1d1f"), colors.HexColor("#6e6e73"), colors.HexColor("#d2d2d7")
OK, BAD, NA = colors.HexColor("#248a3d"), colors.HexColor("#d70015"), MUTED
styles = getSampleStyleSheet()
for _name, _size in (("Title", 20), ("Heading2", 13), ("Heading3", 10.5)):
    styles[_name].alignment, styles[_name].fontSize, styles[_name].leading = TA_LEFT, _size, _size * 1.25
    styles[_name].fontName, styles[_name].textColor = "Helvetica-Bold", INK
styles["Title"].spaceAfter = 2
styles["BodyText"].textColor = INK
SMALL = ParagraphStyle("small", parent=styles["BodyText"], fontSize=8, leading=10)
MONO = ParagraphStyle("mono", parent=SMALL, fontName="Courier", fontSize=7, leading=9)
EYEBROW = ParagraphStyle("eyebrow", parent=SMALL, fontName="Helvetica-Bold", fontSize=7, leading=9, textColor=MUTED)


def _qr(url: str, size=24 * mm) -> Image:
    buf = io.BytesIO()
    qrcode.make(url, box_size=4, border=1).save(buf, "PNG")
    buf.seek(0)
    return Image(buf, width=size, height=size)


def _thumb(ev) -> Image | Paragraph:
    if not ev.mime.startswith("image/") or not storage.exists(ev.storage_key):
        return Paragraph(ev.mime, SMALL)
    try:
        img = PILImage.open(io.BytesIO(storage.load(ev.storage_key))).convert("RGB")
    except OSError:
        return Paragraph(ev.mime, SMALL)
    img.thumbnail((300, 300))
    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=80)
    buf.seek(0)
    ratio = img.height / img.width
    return Image(buf, width=29 * mm, height=29 * mm * ratio)


def _status(ok) -> Paragraph:
    text, color = ("PASS", OK) if ok is True else ("FAIL", BAD) if ok is False else ("N/A", NA)
    return Paragraph(f'<font color="{color.hexval()}"><b>{text}</b></font>', SMALL)


def _table(rows, widths, header=True) -> Table:
    t = Table(rows, colWidths=widths, repeatRows=1 if header else 0)
    style = [
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("TEXTCOLOR", (0, 0), (-1, -1), INK),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LINEBELOW", (0, 0), (-1, -1), 0.4, RULE),
        ("LEFTPADDING", (0, 0), (-1, -1), 3),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 3.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3.5),
    ]
    if header:
        style += [("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, 0), 7),
                  ("TEXTCOLOR", (0, 0), (-1, 0), MUTED), ("LINEBELOW", (0, 0), (-1, 0), 0.8, INK)]
    else:
        # Label / value tables: labels muted, in the first column (and the third in two-pair rows).
        style += [("TEXTCOLOR", (0, 0), (0, -1), MUTED)] + ([("TEXTCOLOR", (2, 0), (2, -1), MUTED)] if len(widths) == 4 else [])
    t.setStyle(TableStyle(style))
    return t


def build_report(case, evidence, chain, verification, users: dict, generated_by, generated_at: str) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=15 * mm, bottomMargin=15 * mm,
                            title=f"ChainProof report — {case.title}", author="ChainProof")
    name = lambda uid: users[uid].name if uid in users else uid  # noqa: E731
    story = [
        Paragraph("CHAINPROOF · CASE EVIDENCE REPORT", EYEBROW),
        Paragraph(case.title, styles["Title"]),
        _table([
            ["Case", case.title, "Reference", case.id[:8].upper()],
            ["Status", case.status, "Current custodian", name(case.custodian_id)],
            ["Opened", utc_text(case.created_at), "Generated", utc_text(generated_at)],
            ["Generated by", f"{generated_by.name} ({generated_by.role})", "Evidence items", str(len(evidence))],
        ], [28 * mm, 62 * mm, 32 * mm, 58 * mm], header=False),
        Spacer(1, 4 * mm),
    ]
    if case.description:
        story += [Paragraph(case.description, styles["BodyText"]), Spacer(1, 4 * mm)]

    ok = verification["ok"]
    banner = "All integrity checks passed" if ok else "Integrity check failed: see the details below"
    story += [
        Paragraph(f'<font color="{(OK if ok else BAD).hexval()}"><b>{banner}</b></font>', styles["Heading2"]),
        Paragraph(
            f"Chain of custody: {verification['chain']['length']} entries, "
            + ("unbroken, every entry signed by the server." if verification["chain"]["ok"]
               else f"broken at entry #{verification['chain']['broken_at']}: {verification['chain']['reason']}."),
            styles["BodyText"],
        ),
        Paragraph(f"Trusted timestamp of the log: {describe_anchors(verification['anchors'])}. Anyone can later check that "
                  "this hash still sits at that entry: a rewritten log can't match it.", SMALL),
        Spacer(1, 4 * mm),
        Paragraph("Evidence", styles["Heading2"]),
    ]

    checks_by_id = {c["evidence_id"]: c for c in verification["evidence"]}
    for i, ev in enumerate(evidence, start=1):
        m, chk = ev.manifest_json, checks_by_id[ev.id]["checks"]
        gps = m.get("gps")
        gps_text = f'{gps["lat"]:.6f}, {gps["lon"]:.6f} (±{gps.get("accuracy") or "?"} m)' if gps else "not recorded"
        verdict = (ev.forensics_json or {}).get("label", "not analysed")
        info = _table([
            ["File", Paragraph(ev.filename, SMALL)],
            ["SHA-256", Paragraph(ev.sha256, MONO)],
            ["Provenance", "Signed on device at capture" if ev.provenance == "device_signed" else "Imported (no capture signature)"],
            ["Captured", f'{utc_text(m["captured_at"])} (device clock)' if m.get("captured_at") else "unknown"],
            ["Location", gps_text],
            ["Received", utc_text(ev.received_at)],
            ["Trusted timestamp", f"existed by {utc_text(ev.tsa_time)} (FreeTSA)" if ev.tsa_time else ev.tsa_status],
            ["Photo forensics", verdict],
        ], [30 * mm, 72 * mm], header=False)
        checks = _table(
            [["Check", "Result"]] + [[k.replace("_", " ").capitalize(), _status(v["ok"])] for k, v in chk.items()],
            [30 * mm, 14 * mm],
        )
        verify_url = f"{settings.public_base_url}/verify/{ev.sha256}"
        right = [checks, Spacer(1, 2 * mm), _qr(verify_url), Paragraph("Scan to verify", SMALL)]
        story.append(KeepTogether([
            Paragraph(f"E{i}. {ev.filename}", styles["Heading3"]),
            Table([[_thumb(ev), info, right]], colWidths=[32 * mm, 104 * mm, 44 * mm],
                  style=[("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (-1, -1), 0)]),
            Spacer(1, 3 * mm),
        ]))

    story += [PageBreak(), Paragraph("Chain of custody", styles["Heading2"]),
              Paragraph("Each entry's hash covers its content and the previous entry's hash. Changing or removing any entry breaks every link after it.", SMALL),
              Spacer(1, 2 * mm)]
    ev_index = {ev.id: f"E{i}" for i, ev in enumerate(evidence, start=1)}
    rows = [["#", "Time (UTC)", "Action", "By", "Item", "Entry hash"]]
    for e in chain:
        rows.append([str(e["seq"]), Paragraph(utc_text(e["ts"]).removesuffix(" UTC"), SMALL), e["action"],
                     Paragraph(name(e["actor_id"]) if e["actor_id"] != "system" else "system", SMALL),
                     ev_index.get(e["evidence_id"], ""), Paragraph(e["entry_hash"][:32] + "…", MONO)])
    story.append(_table(rows, [9 * mm, 30 * mm, 26 * mm, 32 * mm, 11 * mm, 72 * mm]))
    story += [Spacer(1, 6 * mm), Paragraph(
        "This report is registered with ChainProof by its SHA-256 hash when it is generated. Upload this PDF to the public verify "
        f"page ({settings.public_base_url}/verify) to confirm it has not been altered. Forensic image findings are indicators, not proof.",
        SMALL)]

    def footer(canvas, doc_):
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(MUTED)
        canvas.drawString(15 * mm, 8 * mm, f"ChainProof · case {case.id[:8].upper()} · generated {utc_text(generated_at)}")
        canvas.drawRightString(A4[0] - 15 * mm, 8 * mm, f"Page {doc_.page}")
        canvas.restoreState()

    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()
